import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsIn,
  IsMongoId,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
} from 'class-validator';
import {
  ITEM_VIEW_TYPES,
  ITEM_VIEW_VISITOR_ID_PATTERN,
} from '../item-view.constants';
import type { ItemViewType } from '../item-view.constants';

/**
 * Public beacon body. The global `forbidNonWhitelisted` pipe rejects any extra field, so a
 * caller can never smuggle a `storeId` — the store is always derived from the item.
 */
export class TrackItemViewDto {
  @ApiProperty({ enum: ITEM_VIEW_TYPES })
  @IsIn([...ITEM_VIEW_TYPES])
  itemType: ItemViewType;

  @ApiProperty({ description: 'Product or Box ObjectId.' })
  @IsMongoId()
  itemId: string;

  @ApiPropertyOptional({
    description:
      'Anonymous visitor id generated by the storefront: a UUID v4 or a 32-character hex value.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(64)
  @Matches(ITEM_VIEW_VISITOR_ID_PATTERN, {
    message: 'visitorId must be a UUID or a 32-character hexadecimal id',
  })
  visitorId?: string;
}
