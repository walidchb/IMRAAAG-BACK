import { ANALYTICS_TIMEZONE } from '../analytics/constants/analytics.constants';

/**
 * Product & Box view analytics vocabulary.
 *
 * One aggregate row per `(storeId, itemType, itemId, Algiers day, visitorHash)`. Products and
 * Boxes are separate `itemType`s (never merged into one untyped counter). This file is pure
 * vocabulary — no database access.
 */

/** The two public item kinds that can be viewed. */
export const ITEM_VIEW_TYPES = ['product', 'box'] as const;
export type ItemViewType = (typeof ITEM_VIEW_TYPES)[number];

/** Read scopes: both kinds, or one. `all` is a filter, never a stored value. */
export const ITEM_VIEW_SCOPES = ['all', 'product', 'box'] as const;
export type ItemViewScope = (typeof ITEM_VIEW_SCOPES)[number];

/** Ranking dimension for the items list. */
export const ITEM_VIEW_SORTS = ['views', 'unique'] as const;
export type ItemViewSort = (typeof ITEM_VIEW_SORTS)[number];

/** Every day boundary is the Algiers calendar day (UTC+1, no DST). */
export const ITEM_VIEW_TIMEZONE = ANALYTICS_TIMEZONE;

/** Stored hash length (`sha256(...).slice(0, 32)`). */
export const ITEM_VIEW_HASH_LENGTH = 32;

/**
 * The visitor id is generated by the storefront as a v4 UUID (`crypto.randomUUID`) or, on
 * older/restricted browsers, a 32-character hex value (`crypto.getRandomValues`). Accept only
 * those shapes so arbitrary short strings cannot mint an unlimited number of "unique" rows.
 */
export const ITEM_VIEW_VISITOR_ID_PATTERN =
  /^(?:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|[0-9a-f]{32})$/i;

/** Default read preset for the views surface (Sales keeps its own 30d default). */
export const ITEM_VIEW_DEFAULT_PRESET = '7d' as const;

/**
 * Conservative bot/unfurl/automation User-Agent tokens. Best-effort only — this is a quality
 * filter, not a security boundary. Matching is case-insensitive and substring-based.
 */
export const ITEM_VIEW_BOT_UA_REGEX =
  /bot|crawler|spider|preview|headless|puppeteer|playwright|phantom|selenium|curl|wget|python-requests|httpclient|facebookexternalhit|whatsapp|telegram|slack|discord|twitterbot|linkedin|pinterest|skype|googlebot|bingbot|yandex|baidu|duckduck|semrush|ahrefs|mj12bot|dotbot|petalbot|applebot|embedly|quora|outbrain|flipboard|feedfetcher|adsbot|lighthouse|pagespeed|gtmetrix|pingdom|uptime|monitor|libwww|go-http-client|okhttp|node-fetch|undici/i;

/** True when the User-Agent should not be counted (missing/empty or an automation token). */
export function isIgnoredUserAgent(userAgent: string | undefined | null): boolean {
  if (!userAgent || !userAgent.trim()) return true;
  return ITEM_VIEW_BOT_UA_REGEX.test(userAgent);
}
